"""Rebuild bundled BSC5 stars and CC-BY constellation lines; see public/sky-sources.txt."""
import csv, gzip, io, json, urllib.request
from pathlib import Path

def fetch(url):
    return urllib.request.urlopen(url).read()

rows = list(csv.reader(io.StringIO(fetch('https://raw.githubusercontent.com/MarcvdSluys/ConstellationLines/master/ConstellationLines.csv').decode())))
figures = [[r[0].strip(), [int(v) for v in r[2:] if v.strip()]] for r in rows[1:] if r and not r[0].startswith('#')]
anchors = {s for _, line in figures for s in line}
stars = []
for s in gzip.decompress(fetch('https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz')).decode().splitlines():
    if not s[75:77].strip(): continue
    hr, mag = int(s[:4]), float(s[102:107])
    if mag > 5.5 and hr not in anchors: continue
    ra = 15 * (int(s[75:77]) + int(s[77:79])/60 + float(s[79:83])/3600)
    dec = (int(s[84:86]) + int(s[86:88])/60 + int(s[88:90])/3600) * (-1 if s[83] == '-' else 1)
    stars.append([hr, round(ra,6), round(dec,6), mag, float(s[109:114].strip() or '0.5'), float(s[148:154].strip() or '0'), float(s[154:160].strip() or '0')])
ids = {s[0] for s in stars}
assert anchors <= ids, anchors - ids
Path('src/data/skyCatalog.mjs').write_text('// Generated by scripts/build-sky-catalog.py. Attribution: /sky-sources.txt\nexport const stars = '+json.dumps(stars,separators=(',',':'))+'\nexport const figures = '+json.dumps(figures,separators=(',',':'))+'\n')
print(f'{len(stars)} stars; {len(figures)} line figures')
